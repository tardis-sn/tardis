"""Exact reader-facing cases from the single-shell manuscript catalog.

Lengths and velocities use the explorer's declared illustrative units.
Source labels are audit references and are not reader-facing categories.
"""

from dataclasses import dataclass
from math import sqrt

from .model import ExplorerInputs


@dataclass(frozen=True)
class Preset:
    """Reproducible shell, ray, and target with qualitative expectations.

    Parameters
    ----------
    name : str
        Descriptive selector label.
    inputs : ExplorerInputs
        Exact canonical inputs.
    description : str
        Geometric and resonance behavior for the detail card.
    source_crosswalk : str
        Manuscript cases used in the audit.
    expected_ray_family : str
        Nominal ray itinerary.
    expected_shape_family : str
        Active projected-velocity topology.
    expected_turn_count : int
        Active sign-changing gradient-zero count.
    expected_crossing_count : int or None
        Distinct physical crossing count, if not a delicate contact limit.
    """

    name: str
    inputs: ExplorerInputs
    description: str
    source_crosswalk: str
    expected_ray_family: str
    expected_shape_family: str
    expected_turn_count: int
    expected_crossing_count: int | None


def _make_preset(
    name: str,
    b: float,
    x_0: float,
    m: float,
    q: float,
    w: float,
    path: str,
    shape: str,
    turns: int,
    crossings: int | None,
    description: str,
    source: str,
    *,
    r_in: float = 1.0,
    r_out: float = 3.0,
    s_stop: float | None = None,
) -> Preset:
    """Convert a paper's slope/intercept case to canonical edge velocities."""
    inputs = ExplorerInputs(
        r_in=r_in,
        r_out=r_out,
        v_in=m * r_in + q,
        v_out=m * r_out + q,
        b=b,
        x_0=x_0,
        w=w,
        s_stop=s_stop,
    )
    return Preset(
        name, inputs, description, source, path, shape, turns, crossings
    )


